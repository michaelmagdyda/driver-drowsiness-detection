/**
 * Make one real checkpoint the active model for every user of the system.
 * In-memory only for this process - a restart falls back to the
 * server-configured default. Admin only.
 * @param {string} id
 */
export async function activateModelCheckpoint(id) {
  const data = await authFetch(`/admin/models/activate`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ id }),
  });
  return data.map(mapModelCheckpoint);
}

