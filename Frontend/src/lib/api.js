/**
 * Rebuild the active checkpoint at a new minimum detection score. The
 * threshold is baked into the network at construction time, so this reloads
 * the model - in-memory only, resets to MODEL_SCORE_THRESHOLD on restart.
 * Admin only.
 * @param {number} scoreThreshold In [0, 1].
 */
export async function setConfidenceThreshold(scoreThreshold) {
  const data = await authFetch(`/admin/models/threshold`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ score_threshold: scoreThreshold }),
  });
  return {
    architecture: data.architecture,
    device: data.device,
    numClasses: data.num_classes,
    scoreThreshold: data.score_threshold,
  };
}

/**
 * Rebuild the active checkpoint targeting a new compute backend. A "gpu"
 * request always succeeds - it picks the best GPU execution provider
 * actually available on the server host and falls back to CPU silently when
 * none is (e.g. in production, which has no GPU at all); compare the
 * returned `device` against what was requested to tell a real switch from a
 * fallback. In-memory only, resets to MODEL_DEVICE on restart. Admin only.
 * @param {"cpu" | "gpu"} device
 */
export async function setComputeDevice(device) {
  const data = await authFetch(`/admin/models/device`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ device }),
  });
  return {
    architecture: data.architecture,
    device: data.device,
    numClasses: data.num_classes,
    scoreThreshold: data.score_threshold,
  };
}

/**
 * Run drowsiness detection on a single image file.
 * @param {File} file
 * @returns {Promise<{
 *   driverState: string, alertLevel: string, fatigueScore: number,
 *   detections: Array<{ label: string, labelIndex: number, score: number, box: { x1:number,y1:number,x2:number,y2:number } }>,
 *   metrics: { eyeAspectRatio: number|null, mouthAspectRatio: number|null, eyesClosed: boolean, yawning: boolean },
 *   inferenceMs: number, imageWidth: number, imageHeight: number,
 * }>}
 */
export async function analyzeImage(file) {
  const body = new FormData();
  body.append("file", file);

  let response;
  try {
    response = await fetch(`${API_URL}/analysis/image`, { method: "POST", body });
  } catch {
    throw new ApiError("Could not reach the analysis service. Is the backend running?");
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok || !payload?.success) {
    throw new ApiError(payload?.message || `Analysis failed (HTTP ${response.status}).`, {
      errorCode: payload?.error_code,
      status: response.status,
    });
  }

  const data = payload.data;
  return {
    driverState: data.driver_state,
    alertLevel: data.alert_level,
    fatigueScore: data.fatigue_score,
    detections: data.detections.map((det) => ({
      label: det.label,
      labelIndex: det.label_index,
      score: det.score,
      box: det.box,
    })),
    metrics: {
      eyeAspectRatio: data.metrics.eye_aspect_ratio,
      mouthAspectRatio: data.metrics.mouth_aspect_ratio,
      eyesClosed: data.metrics.eyes_closed,
      yawning: data.metrics.yawning,
    },
    inferenceMs: data.inference_ms,
    imageWidth: data.image_width,
    imageHeight: data.image_height,
  };
}

function mapDetection(det) {
  return { label: det.label, labelIndex: det.label_index, score: det.score, box: det.box };
}

/**
 * Run drowsiness detection on an uploaded video by sampling frames through
 * the same detector used for images. The backend decides the sample rate
 * actually used (it may differ from `sampleRate`, e.g. for a long clip) and
 * every field below reflects what was actually analysed.
 * @param {File} file
 * @param {number} [sampleRate] Requested samples per second.
 */
export async function analyzeVideo(file, sampleRate = 2) {
  const body = new FormData();
  body.append("file", file);
  body.append("sample_rate", String(sampleRate));

  let response;
  try {
    response = await fetch(`${API_URL}/analysis/video`, { method: "POST", body });
  } catch {
    throw new ApiError("Could not reach the analysis service. Is the backend running?");
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok || !payload?.success) {
    throw new ApiError(payload?.message || `Analysis failed (HTTP ${response.status}).`, {
      errorCode: payload?.error_code,
      status: response.status,
    });
  }

  const data = payload.data;
  return {
    videoDurationSec: data.video_duration_sec,
    videoWidth: data.video_width,
    videoHeight: data.video_height,
    sourceFps: data.source_fps,
    sourceFrameCount: data.source_frame_count,
    sampleFps: data.sample_fps,
    sampledFrameCount: data.sampled_frame_count,
    summary: {
      driverState: data.summary.driver_state,
      alertLevel: data.summary.alert_level,
      fatigueScore: data.summary.fatigue_score,
      maxFatigueScore: data.summary.max_fatigue_score,
      totalYawns: data.summary.total_yawns,
      longestEyeClosureSec: data.summary.longest_eye_closure_sec,
      avgEyeAspectRatio: data.summary.avg_eye_aspect_ratio,
      avgMouthAspectRatio: data.summary.avg_mouth_aspect_ratio,
      avgConfidence: data.summary.avg_confidence,
      totalAlerts: data.summary.total_alerts,
      sessionDurationSec: data.summary.session_duration_sec,
    },
    frames: data.frames.map((f) => ({
      t: f.t,
      driverState: f.driver_state,
      alertLevel: f.alert_level,
      fatigueScore: f.fatigue_score,
      eyeAspectRatio: f.eye_aspect_ratio,
      mouthAspectRatio: f.mouth_aspect_ratio,
      confidence: f.confidence,
      detections: f.detections.map(mapDetection),
    })),
    timeline: data.timeline.map((e) => ({ t: e.t, kind: e.kind, label: e.label })),
    distribution: data.distribution.map((d) => ({ state: d.state, count: d.count })),
    // The backend burns real detection boxes + a state/fatigue HUD directly
    // onto every frame and re-encodes to H.264 - a genuine annotated video,
    // not the raw upload. `null` when one wasn't generated (very long clip,
    // or the encoder failed) - never a fabricated link.
    previewUrl: data.preview_video_url ? `${API_URL}${data.preview_video_url}` : null,
  };
}

/**
 * Submit one completed webcam monitoring session: the MediaRecorder
 * recording plus every event collected locally via analyzeImage() during
 * the session. One-shot - there is no separate start/append/finish call.
 * @param {{ events: Array<object>, startedAt: Date, recordingBlob: Blob }} params
 */
export async function completeSession({ events, startedAt, recordingBlob }) {
  const body = new FormData();
  body.append("recording", recordingBlob, "session.webm");
  body.append(
    "events",
    JSON.stringify(
      events.map((e) => ({
        t: e.t,
        ear: e.ear ?? null,
        mar: e.mar ?? null,
        eye_closed: e.eyeClosed,
        yawning: e.yawning,
        state: e.driverState,
        alert_level: e.alertLevel,
        fatigue_score: e.fatigueScore,
        detections: e.detections.map((d) => ({
          label: d.label,
          label_index: d.labelIndex,
          score: d.score,
          box: d.box,
        })),
      })),
    ),
  );
  body.append("started_at", startedAt.toISOString());

  const {
    data: { session },
  } = await supabase.auth.getSession();
  if (!session?.access_token) {
    throw new ApiError("You must be signed in to save a session.", {
      errorCode: "AUTH_REQUIRED",
      status: 401,
    });
  }

  let response;
  try {
    response = await fetch(`${API_URL}/sessions`, {
      method: "POST",
      body,
      headers: { Authorization: `Bearer ${session.access_token}` },
    });
  } catch {
    throw new ApiError("Could not reach the backend. Is it running?");
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok || !payload?.success) {
    throw new ApiError(payload?.message || `Saving the session failed (HTTP ${response.status}).`, {
      errorCode: payload?.error_code,
      status: response.status,
    });
  }
  return mapSession(payload.data);
}

