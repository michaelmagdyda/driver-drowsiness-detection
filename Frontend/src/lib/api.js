// Client for the Driver Drowsiness Detection FastAPI backend.
// Every endpoint returns { success, message, data } or
// { success: false, message, error_code, errors } - see Backend/CONTRACT.md.
import { supabase } from "@/integrations/supabase/client";

const API_URL = import.meta.env.VITE_API_URL || "http://127.0.0.1:8000/api/v1";

export class ApiError extends Error {
  constructor(message, { errorCode, status } = {}) {
    super(message);
    this.name = "ApiError";
    this.errorCode = errorCode;
    this.status = status;
  }
}

// Sessions/analytics/admin all require a Supabase-issued access token, which
// the backend verifies itself (app/dependencies/auth.py) rather than trusting
// Supabase's RLS - see Backend's "service-role bypasses RLS" note.
async function authFetch(path, options = {}) {
  const {
    data: { session },
  } = await supabase.auth.getSession();
  if (!session?.access_token) {
    throw new ApiError("You must be signed in to do this.", {
      errorCode: "AUTH_REQUIRED",
      status: 401,
    });
  }

  let response;
  try {
    response = await fetch(`${API_URL}${path}`, {
      ...options,
      headers: { ...options.headers, Authorization: `Bearer ${session.access_token}` },
    });
  } catch {
    throw new ApiError("Could not reach the backend. Is it running?");
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok || !payload?.success) {
    throw new ApiError(payload?.message || `Request failed (HTTP ${response.status}).`, {
      errorCode: payload?.error_code,
      status: response.status,
    });
  }
  return payload.data;
}

function mapPagination(p) {
  return {
    page: p.page,
    pageSize: p.page_size,
    totalItems: p.total_items,
    totalPages: p.total_pages,
    hasNext: p.has_next,
    hasPrevious: p.has_previous,
  };
}

function mapSession(s) {
  return {
    id: s.id,
    source: s.source,
    status: s.status,
    startedAt: s.started_at,
    endedAt: s.ended_at,
    durationSeconds: s.duration_seconds,
    totalEvents: s.total_events,
    totalAlerts: s.total_alerts,
    yawnCount: s.yawn_count,
    eyeClosureSeconds: s.eye_closure_seconds,
    maxFatigueScore: s.max_fatigue_score,
    finalState: s.final_state,
    alertLevel: s.alert_level,
    createdAt: s.created_at,
  };
}

/**
 * List the signed-in user's monitoring sessions, newest first.
 * @param {{ page?: number, pageSize?: number }} [opts]
 */
export async function listSessions({ page = 1, pageSize = 20 } = {}) {
  const data = await authFetch(`/sessions?page=${page}&page_size=${pageSize}`);
  return { items: data.items.map(mapSession), pagination: mapPagination(data.pagination) };
}

/**
 * Get one session owned by the signed-in user.
 * @param {string} sessionId
 */
export async function getSession(sessionId) {
  const data = await authFetch(`/sessions/${sessionId}`);
  return {
    ...mapSession(data),
    mediaId: data.media_id,
    updatedAt: data.updated_at,
    // `media` is only present once the session has a recording generated by
    // POST /sessions - null for sessions with no stored file.
    media: data.media
      ? {
          bucket: data.media.bucket,
          storagePath: data.media.storage_path,
          mimeType: data.media.mime_type,
        }
      : null,
  };
}

/**
 * Permanently delete one session owned by the signed-in user - its detection
 * events, its linked recording, and the session row itself.
 * @param {string} sessionId
 */
export async function deleteSession(sessionId) {
  await authFetch(`/sessions/${sessionId}`, { method: "DELETE" });
}

/**
 * List one session's detection events (the frame-by-frame timeline), oldest first.
 * @param {string} sessionId
 * @param {{ page?: number, pageSize?: number }} [opts]
 */
export async function listSessionEvents(sessionId, { page = 1, pageSize = 100 } = {}) {
  const data = await authFetch(`/sessions/${sessionId}/events?page=${page}&page_size=${pageSize}`);
  return {
    items: data.items.map((e) => ({
      id: e.id,
      ts: e.ts,
      ear: e.ear,
      mar: e.mar,
      headPitch: e.head_pitch,
      headYaw: e.head_yaw,
      headRoll: e.head_roll,
      eyeClosed: e.eye_closed,
      yawning: e.yawning,
      state: e.state,
      fatigueScore: e.fatigue_score,
      alertLevel: e.alert_level,
      detections: (e.detections ?? []).map(mapDetection),
      confidence: e.confidence,
    })),
    pagination: mapPagination(data.pagination),
  };
}

